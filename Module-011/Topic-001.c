/*
  Topic: Recursion in C
  
  Definition:
  Recursion is a programming technique where a function calls itself directly or indirectly 
  to solve a smaller instance of the same problem. Every recursive function must have a 
  base case (stopping condition) to terminate execution and prevent infinite loops.

  Where We Use It:
  - Tree and Graph Data Structure traversals (e.g., Binary Tree, BST).
  - Divide and Conquer algorithms (e.g., Merge Sort, Quick Sort, Binary Search).
  - Mathematical problem-solving (e.g., Factorial, Fibonacci Series, GCD, Power calculation).
  - Backtracking problems (e.g., N-Queens, Sudoku Solver, Maze routing).

  Why We Use It:
  - Code Simplicity: Complex problems can be broken down into smaller sub-problems, 
    making solutions easier and cleaner to write.
  - Clean Structure: It simplifies code for complex data structures and hierarchical traversal 
    compared to complex iterative loops.
*/