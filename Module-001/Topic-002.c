// File: topic-002.c

#include <stdio.h>

int main() 
{
    int num1 = 20;   // Integer variable
    float f = 2.5;   // Float variable for decimals
    char b = 'R';    // Character variable for a single character

    // Printing all variables using their format specifiers
    printf("Integer value: %d\n", num1);
    printf("Float value: %f\n", f);
    printf("Character value: %c\n", b);

    return 0;
}