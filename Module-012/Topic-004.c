/*
  Topic: Types of Matrices in Mathematics & 2D Arrays
  
  Complete List of Matrix Types discussed:

  1. Row Matrix:
     - Definition: A matrix that has only one row (Order: 1 x n).
     - Example: [ 1  4  7  9 ]

  2. Column Matrix / Column Vector:
     - Definition: A matrix that has only one column (Order: m x 1).
     - Example: 
       [ 2 ]
       [ 5 ]
       [ 8 ]

  3. Zero / Null Matrix:
     - Definition: A matrix where all elements are zero (0).
     - Example:
       [ 0  0 ]
       [ 0  0 ]

  4. Diagonal Matrix:
     - Definition: A square matrix where all elements outside the main diagonal are zero (i != j implies a[i][j] == 0).
     - Example:
       [ 5  0  0 ]
       [ 0  8  0 ]
       [ 0  0  2 ]

  5. Scalar Matrix:
     - Definition: A diagonal matrix where all the main diagonal elements are equal and non-zero, and all other elements are zero.
     - Example:
       [ 7  0  0 ]
       [ 0  7  0 ]
       [ 0  0  7 ]

  6. Unit Matrix / Identity Matrix:
     - Definition: A diagonal matrix where all the main diagonal elements are strictly 1, and all other elements are zero (i == j implies a[i][j] == 1, i != j implies a[i][j] == 0).
     - Example:
       [ 1  0  0 ]
       [ 0  1  0 ]
       [ 0  0  1 ]

  7. Square Matrix:
     - Definition: A matrix where the number of rows is equal to the number of columns (r == c).
     - Example:
       [ 1  2  3 ]
       [ 4  5  6 ]
       [ 7  8  9 ]
*/