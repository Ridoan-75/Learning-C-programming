/*
  What is an Array?
  An array is a collection of variables of the same data type stored at 
  contiguous (adjacent) memory locations. In a normal variable, you can 
  store only one value (e.g., int x = 10;). But an array is like a container 
  with multiple slots where you can store many values under a single variable name.

  Why do we use it?
  1. Manage Multiple Data Easily: Instead of creating 50 different variables 
     (num1, num2, num3... num50), you can just create one array (int num[50];) 
     to store all 50 values.
  2. Easy with Loops: Because array elements have index numbers (starting from 0), 
     you can easily use for or while loops to input, process, or print thousands 
     of items in just 2-3 lines of code.
  3. Clean & Organized Code: It keeps your code short, readable, and structured 
     instead of creating a mess with endless variables.
  4. Fast Random Access: If you know the index (e.g., arr[5]), you can directly 
     jump to and access that specific element instantly.
*/